use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;

use serde_json::Value;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    match args.get(1).map(String::as_str) {
        Some("text4") if args.len() == 4 => text4(&args[2], &args[3]),
        Some("build") if args.len() == 4 => {
            let mut total = 0;
            for (name, size) in datagen::build_all(args[2].as_ref(), args[3].as_ref()) {
                println!("{size:>8}  {name}");
                total += size;
            }
            println!("{total:>8}  total");
        }
        _ => {
            eprintln!("usage: datagen text4 <text4.json> <out.rs>\n       datagen build <exports-dir> <blobs-dir>");
            std::process::exit(1);
        }
    }
}

fn u16s(v: &Value) -> Vec<u16> {
    v.as_array()
        .unwrap()
        .iter()
        .map(|x| x.as_u64().unwrap() as u16)
        .collect()
}

fn text4(input: &str, output: &str) {
    let j: Value = serde_json::from_slice(&fs::read(input).unwrap()).unwrap();
    let int = u16s(&j["table_int"]);
    let kor = u16s(&j["table_kor"]);
    let kor_start = j["table_kor_start"].as_u64().unwrap() as u16;

    // PKHeX ConvertChar2ValueG4 returns the first index in TableINT, then TableKOR.
    let mut reverse: BTreeMap<u16, u16> = BTreeMap::new();
    for (i, &c) in kor.iter().enumerate().rev() {
        reverse.insert(c, kor_start + i as u16);
    }
    for (i, &c) in int.iter().enumerate().rev() {
        reverse.insert(c, i as u16);
    }
    reverse.remove(&0xFFFF);

    let mut out = String::new();
    writeln!(
        out,
        "//! Generated by `datagen text4` from PKHeX {} `StringConverter4Util` tables.\n",
        j["pkhex_version"].as_str().unwrap_or("?")
    )
    .unwrap();
    let table = |out: &mut String, name: &str, vals: &[u16]| {
        writeln!(
            out,
            "#[rustfmt::skip]\npub static {name}: [u16; {}] = [",
            vals.len()
        )
        .unwrap();
        for chunk in vals.chunks(12) {
            let line: Vec<_> = chunk.iter().map(|v| format!("0x{v:04X}")).collect();
            writeln!(out, "    {},", line.join(", ")).unwrap();
        }
        writeln!(out, "];\n").unwrap();
    };
    writeln!(out, "pub const KOR_START: u16 = 0x{kor_start:04X};\n").unwrap();
    table(&mut out, "TABLE_INT", &int);
    table(&mut out, "TABLE_KOR", &kor);
    writeln!(
        out,
        "/// (unicode, gen 4 value) sorted by unicode.\n#[rustfmt::skip]\npub static REVERSE: [(u16, u16); {}] = [",
        reverse.len()
    )
    .unwrap();
    let pairs: Vec<_> = reverse.iter().collect();
    for chunk in pairs.chunks(6) {
        let line: Vec<_> = chunk
            .iter()
            .map(|(c, v)| format!("(0x{c:04X}, 0x{v:04X})"))
            .collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
    fs::write(output, out).unwrap();
}
