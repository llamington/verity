#!/usr/bin/env python3
"""Regenerates data/events4.tsv: language, region and games for every Gen 4 Wonder Card.

PKHeX's database has no availability metadata, so this joins it byte for byte against the
EventsGallery repository (see docs/research/events-region.md).

Usage: gen-events4-manifest.py <EventsGallery checkout> <gifts4.json> <out.tsv>
Run with `python3 -I`.
"""
import os
import re
import struct
import subprocess
import sys

LANG = {"JPN": 1, "ENG": 2, "FRE": 3, "ITA": 4, "GER": 5, "SPA": 7, "KOR": 8}
REGION = {"NA": 1, "UK": 2, "AU": 3, "EU": 4}
GAME_BITS = [("Pt", 4), ("HG", 8), ("SS", 16), ("D", 1), ("P", 2)]
BLOCK = [
    "ABCD", "ABDC", "ACBD", "ACDB", "ADBC", "ADCB", "BACD", "BADC", "BCAD", "BCDA", "BDAC", "BDCA",
    "CABD", "CADB", "CBAD", "CBDA", "CDAB", "CDBA", "DABC", "DACB", "DBAC", "DBCA", "DCAB", "DCBA",
]


def crypt(buf, seed):
    out = bytearray()
    for i in range(0, len(buf), 2):
        seed = (seed * 0x41C64E6D + 0x6073) & 0xFFFFFFFF
        out += struct.pack("<H", struct.unpack_from("<H", buf, i)[0] ^ (seed >> 16))
    return bytes(out)


def decrypt_pk4(pk):
    pid, _, chk = struct.unpack_from("<IHH", pk)
    body = crypt(pk[8:0x88], chk)
    order = BLOCK[((pid >> 13) & 31) % 24]
    blocks = {order[i]: body[i * 32:(i + 1) * 32] for i in range(4)}
    return pk[:8] + b"".join(blocks[c] for c in "ABCD") + crypt(pk[0x88:0xEC], pid)


def normalise(raw):
    """Gallery .wc4 files hold the template decrypted; a .pcd would not."""
    raw = bytearray(raw)
    if raw[0] in (1, 2, 7, 13) and struct.unpack_from("<I", raw, 8 + 0x64)[0] != 0:
        raw[8:8 + 236] = decrypt_pk4(bytes(raw[8:8 + 236]))
    return bytes(raw)


def fnv64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def games_mask(tag):
    mask, i = 0, 0
    while i < len(tag):
        for name, bit in GAME_BITS:
            if tag.startswith(name, i):
                mask |= bit
                i += len(name)
                break
        else:
            raise SystemExit(f"unknown game tag {tag!r}")
    return mask


def main():
    import json

    gallery, export, out = sys.argv[1:4]
    db = json.load(open(export))
    by_bytes = {bytes.fromhex(r["raw"]): r for r in db}
    if len(by_bytes) != len(db):
        raise SystemExit("duplicate cards in the export")

    root = os.path.join(gallery, "Released/Gen 4/Wondercards")
    found = {}
    for d, _, files in os.walk(root):
        lang = os.path.relpath(d, root).split(os.sep)[0]
        for f in files:
            data = open(os.path.join(d, f), "rb").read()
            r = by_bytes.get(normalise(data))
            if r is None:
                raise SystemExit(f"no database entry for {lang}/{f}")
            if r["index"] in found:
                raise SystemExit(f"card {r['index']} appears twice: {f}")
            found[r["index"]] = (lang, f)
    missing = [r["index"] for r in db if r["index"] not in found]
    if missing:
        raise SystemExit(f"cards with no gallery file: {missing}")

    commit = subprocess.run(
        ["git", "-C", gallery, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    with open(out, "w", encoding="utf-8") as o:
        o.write(f"# Generated by scripts/gen-events4-manifest.py from EventsGallery {commit}\n")
        o.write("# index\tcard_id\tlanguage\tregion\tgames\tinjectable\tfnv64\tfile\n")
        for r in sorted(db, key=lambda x: x["index"]):
            lang, name = found[r["index"]]
            m = re.match(r"(\S+) +(\S+) +- ", name)
            if not m:
                raise SystemExit(f"cannot parse {name!r}")
            regions = [REGION[t] for t in re.findall(r"\((NA|UK|AU|EU)\)", name)]
            if len(regions) > 1:
                raise SystemExit(f"two regions in {name!r}")
            injectable = int(r["card_id"] != 0 and "Simulated" not in name)
            o.write(
                f"{r['index']}\t{r['card_id']}\t{LANG[lang]}\t{regions[0] if regions else 0}\t"
                f"{games_mask(m.group(2))}\t{injectable}\t{fnv64(bytes.fromhex(r['raw'])):016x}\t"
                f"{name}\n"
            )


main()
