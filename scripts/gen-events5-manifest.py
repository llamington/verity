#!/usr/bin/env python3
"""Regenerates data/events5.tsv: language and games for every Gen 5 Wonder Card.

PKHeX's database has no availability metadata, so this joins it byte for byte against the
EventsGallery repository (see docs/research/events-region.md).

Usage: gen-events5-manifest.py <EventsGallery checkout> <gifts5.json> <out.tsv>
Run with `python3 -I`.
"""
import json
import os
import re
import struct
import subprocess
import sys

LANG = {"JPN": 1, "ENG": 2, "FRE": 3, "ITA": 4, "GER": 5, "SPA": 7, "KOR": 8}
# Longest names first: "B2" must not parse as "B".
GAME_BITS = [("W2", 4), ("B2", 8), ("W", 1), ("B", 2)]


def fnv64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def games_mask(tag):
    mask, i = 0, 0
    while i < len(tag):
        for name, bit in GAME_BITS:
            if tag.startswith(name, i):
                mask |= bit
                i += len(name)
                break
        else:
            raise SystemExit(f"unknown game tag {tag!r}")
    return mask


def main():
    gallery, export, out = sys.argv[1:4]
    db = [bytes.fromhex(h) for h in json.load(open(export))]
    by_bytes = {raw: i for i, raw in enumerate(db)}
    if len(by_bytes) != len(db):
        raise SystemExit("duplicate cards in the export")

    root = os.path.join(gallery, "Released/Gen 5/Wondercards")
    found = {}
    for d, _, files in os.walk(root):
        lang = os.path.relpath(d, root).split(os.sep)[0]
        for f in files:
            i = by_bytes.get(open(os.path.join(d, f), "rb").read())
            if i is None:
                raise SystemExit(f"no database entry for {lang}/{f}")
            if i in found:
                raise SystemExit(f"card {i} appears twice: {f}")
            found[i] = (lang, f)
    missing = [i for i in range(len(db)) if i not in found]
    if missing:
        raise SystemExit(f"cards with no gallery file: {missing}")

    commit = subprocess.run(
        ["git", "-C", gallery, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    with open(out, "w", encoding="utf-8") as o:
        o.write(f"# Generated by scripts/gen-events5-manifest.py from EventsGallery {commit}\n")
        o.write("# index\tcard_id\tlanguage\tgames\tfnv64\tfile\n")
        for i, raw in enumerate(db):
            lang, name = found[i]
            m = re.match(r"\S+ +([A-Z0-9]+)(?: +\[\w+\])? +- ", name)
            if not m:
                raise SystemExit(f"cannot parse {name!r}")
            card_id = struct.unpack_from("<H", raw, 0xB0)[0]
            o.write(f"{i}\t{card_id}\t{LANG[lang]}\t{games_mask(m.group(1))}\t{fnv64(raw):016x}\t{name}\n")


main()
